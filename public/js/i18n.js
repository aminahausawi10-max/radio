let currentLang = localStorage.getItem('arab_hausa_lang') || 'ha';

function setLanguage(lang) {
  if (!translations[lang]) lang = 'ha';
  currentLang = lang;
  localStorage.setItem('arab_hausa_lang', lang);

  const t = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = t.dir;

  // Update translatable elements
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  // Update direction-sensitive classes
  if (t.dir === 'rtl') {
    document.body.classList.add('rtl-mode');
  } else {
    document.body.classList.remove('rtl-mode');
  }

  // Update active card in language modal
  document.querySelectorAll('.lang-card').forEach((card) => {
    if (card.getAttribute('data-lang') === lang) {
      card.classList.add('active');
    } else {
      card.classList.remove('active');
    }
  });

  // Update header language button indicator
  const langBtnText = document.getElementById('currentLangLabel');
  if (langBtnText) {
    langBtnText.textContent = lang === 'ar' ? 'العربية' : (lang === 'en' ? 'English' : 'Hausa');
  }
}

window.setLanguage = setLanguage;
window.currentLang = currentLang;
