let currentLang = localStorage.getItem('arab_hausa_lang') || 'ha';

function setLanguage(lang) {
  if (!translations[lang]) lang = 'ha';
  currentLang = lang;
  localStorage.setItem('arab_hausa_lang', lang);

  const t = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = t.dir || 'ltr';

  // 1. Update all translatable elements
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  // 2. Update placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) {
      el.placeholder = t[key];
    }
  });

  // 3. Update Ticker Marquee text
  const tickerEl = document.getElementById('tickerMarquee');
  if (tickerEl && t.tickerText) {
    tickerEl.textContent = t.tickerText;
  }

  // 3. Update Language Option Buttons
  document.querySelectorAll('.lang-btn-option').forEach((btn) => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // 4. Update Modal Language Cards
  document.querySelectorAll('.lang-card').forEach((card) => {
    if (card.getAttribute('data-lang') === lang) {
      card.classList.add('active');
    } else {
      card.classList.remove('active');
    }
  });

  // 5. Trigger languageChanged event for dynamic feeds (schedule, news, player)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, t } }));
}

document.addEventListener('DOMContentLoaded', () => {
  // Bind Home Settings language options
  document.querySelectorAll('.lang-btn-option').forEach((btn) => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      setLanguage(lang);
    });
  });

  // Bind Modal language cards
  document.querySelectorAll('.lang-card').forEach((card) => {
    card.addEventListener('click', () => {
      const lang = card.getAttribute('data-lang');
      setLanguage(lang);
    });
  });

  setLanguage(currentLang);
});

window.setLanguage = setLanguage;
window.currentLang = currentLang;
window.translations = translations;
