let currentLang = localStorage.getItem('arab_hausa_lang') || 'ha';

function setLanguage(lang) {
  if (!translations[lang]) lang = 'ha';
  currentLang = lang;
  window.currentLang = lang;
  localStorage.setItem('arab_hausa_lang', lang);

  const t = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = t.dir || 'ltr';

  // Update Page Title
  if (lang === 'en') {
    document.title = "Arab Hausa Radio TV | Diaspora Broadcasting Service";
  } else if (lang === 'ar') {
    document.title = "إذاعة وتلفزيون عرب هوسا | صوت الأمة والتواصل";
  } else {
    document.title = "Arab Hausa Radio TV | Muryar Al'umma da Hadin Kai";
  }

  // Update Header Lang Label
  const headerLangLabel = document.getElementById('headerLangLabel');
  if (headerLangLabel) {
    headerLangLabel.textContent = lang.toUpperCase();
  }

  // 1. Update all translatable elements (safely preserve SVG icons and nested markup)
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      const hasSvg = el.querySelector('svg');
      if (hasSvg) {
        let found = false;
        el.childNodes.forEach(node => {
          if (node.nodeType === 3 && node.nodeValue.trim()) {
            node.nodeValue = ' ' + t[key];
            found = true;
          }
        });
        if (!found) {
          el.insertAdjacentText('beforeend', ' ' + t[key]);
        }
      } else {
        el.textContent = t[key];
      }
    }
  });

  // 2. Update placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) {
      el.placeholder = t[key];
    }
  });

  // 3. Update Ticker Marquee text
  const tickerEl = document.getElementById('tickerMarquee');
  if (tickerEl && t.tickerText) {
    if (typeof window.updateLiveTicker === 'function') {
      window.updateLiveTicker(t.tickerText);
    } else {
      tickerEl.innerHTML = '<span class="ticker-item">' + t.tickerText + ' &nbsp;•&nbsp;</span><span class="ticker-item">' + t.tickerText + ' &nbsp;•&nbsp;</span>';
    }
  }

  // 4. Update Language Option Buttons
  document.querySelectorAll('.lang-btn-option').forEach((btn) => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // 5. Update Modal Language Cards
  document.querySelectorAll('.lang-card').forEach((card) => {
    if (card.getAttribute('data-lang') === lang) {
      card.classList.add('active');
    } else {
      card.classList.remove('active');
    }
  });

  // 6. Trigger languageChanged event for dynamic feeds (schedule, news, player, media)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, t } }));
}

document.addEventListener('DOMContentLoaded', () => {
  // Bind Home Settings language options
  document.querySelectorAll('.lang-btn-option').forEach((btn) => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      setLanguage(lang);
    });
  });

  // Bind Modal language cards
  document.querySelectorAll('.lang-card').forEach((card) => {
    card.addEventListener('click', () => {
      const lang = card.getAttribute('data-lang');
      setLanguage(lang);
    });
  });

  setLanguage(currentLang);
});

window.setLanguage = setLanguage;
window.currentLang = currentLang;
window.translations = translations;
